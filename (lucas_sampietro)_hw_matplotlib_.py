"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

import numpy as np
import matplotlib.pyplot as plt

# Below we will define the initial variables for the beam.
L = 6.0
Ra = 170.0
Rb = 410.0
P = 100.0
q1 = 120.0
q2 = 120.0

# Next, we will define the x-axis variable representing position along the beam.
x = np.linspace(0, L, 500)

# Next, we will initialize the shear variable V as an array of zeros.
V = np.zeros_like(x)

# Then, we will calculate the shear V at each point using the exact piecewise equations provided.
for i in range(len(x)):
    current_x = x[i]
    if current_x < 2.0:
        # Segment 1: x < 2
        V[i] = Ra - (q1 * current_x)
    elif current_x < 4.0:
        # Segment 2: 2 <= x < 4
        V[i] = Ra - (q1 * 2.0) - P
    else:
        # Segment 3: x >= 4
        V[i] = Ra - (q1 * 2.0) - P + Rb - (q2 * (current_x - 4.0))

# Below we will convert kips to lbs for the y-axis.
V_lbs = V * 1000.0

# Next, we will plot the Shear Diagram.
plt.figure(figsize=(8, 4))
plt.plot(x, V_lbs, color='green', linewidth=2, label='Shear (V)')

# Below we will fill the areas between the shear line and the zero reference line.
plt.fill_between(x, V_lbs, 0, color='green', alpha=0.3)

# Then we will create a solid horizontal line at zero.
plt.axhline(0, color='black', linestyle='-', linewidth=0.8)

plt.title('Shear Diagram')
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')

# Finally, we will explicitly set the y-axis ticks and format labels as -100, 100, 200.
plt.yticks([-100000, 100000, 200000], ['-100', '100', '200'])

plt.grid(False)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# Below, we will copy and paste the variables defined in Part 1a.
L = 6.0
Ra = 170.0
Rb = 410.0
P = 100.0
q1 = 120.0
q2 = 120.0

# Then, we will define a variable x using np.linspace().
x = np.linspace(0, L, 500)

# Next, we will define a variable M using np.zeros_like().
M = np.zeros_like(x)

# After that, we will create a for loop to calculate the moment M at each point along the beam using the exact equations provided.
for i in range(len(x)):
    current_x = x[i]
    if current_x < 2.0:
        # Segment 1: x < 2
        M[i] = Ra * current_x - (q1 * (current_x**2) / 2.0)
    elif current_x < 4.0:
        # Segment 2: 2 <= x < 4
        M[i] = (Ra * current_x) - (q1 * 2.0 * (current_x - 1.0)) - (P * (current_x - 2.0))
    else:
        # Segment 3: x >= 4
        M[i] = (Ra * current_x) - (q1 * 2.0 * (current_x - 1.0)) - (P * (current_x - 2.0)) + (Rb * (current_x - 4.0)) - (q2 * (current_x - 4.0) * ((current_x - 4.0) / 2.0))

# Below we will convert kips-ft to lbs-ft for the y-axis
M_lb_ft = M * 1000.0

# Next, we will plot x against M_lb_ft using matplotlib
plt.figure(figsize=(8, 4))
plt.plot(x, M_lb_ft, color='red', linewidth=2, label='Moment (M)')

# Then, we will fill the areas between the moment line and the zero reference line
plt.fill_between(x, M_lb_ft, 0, color='red', alpha=0.3)

# After that, we will create a solid horizontal line at zero.
plt.axhline(0, color='black', linestyle='-', linewidth=0.8)

plt.title('Moment Diagram')
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')

